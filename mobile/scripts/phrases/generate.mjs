#!/usr/bin/env node
// Renders every fixed Swahili phrase in assets/phrases/phrases.json with QVAC
// Chatterbox (multilingual Q4, T3 + S3Gen) and writes assets/phrases/sw/<id>.m4a.
// Then rewrites src/speech/phraseAssets.ts so the app bundles exactly the clips
// that exist.
//
// Chatterbox is far too slow to run live on a phone (C2 spike: 30-47x slower
// than real time on one x86 core), so the app ships these clips instead.
//
// Run on a Linux or macOS machine with @qvac/sdk 0.22.0 installed (the VPS):
//   cd mobile
//   node scripts/phrases/generate.mjs              # only new or changed phrases
//   node scripts/phrases/generate.mjs --force      # everything
//   node scripts/phrases/generate.mjs --only hint_left,hint_right
//   node scripts/phrases/generate.mjs --index-only # just rewrite phraseAssets.ts
// Env: QVAC_SDK=/abs/path/to/node_modules/@qvac/sdk (if `@qvac/sdk` here lacks
// desktop prebuilds), THREADS (ggml threads, default 1), CFM_STEPS (default 2).
// Needs ffmpeg on PATH. Models download on first use into the SDK cache, never
// into the repo.
import { Buffer } from 'node:buffer';
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, writeFileSync, unlinkSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const MOBILE = join(HERE, '..', '..');
const PHRASES_FILE = join(MOBILE, 'assets/phrases/phrases.json');
const OUT_DIR = join(MOBILE, 'assets/phrases/sw');
const LOCK_FILE = join(MOBILE, 'assets/phrases/phrases.lock.json');
const INDEX_FILE = join(MOBILE, 'src/speech/phraseAssets.ts');

const args = process.argv.slice(2);
const force = args.includes('--force');
const indexOnly = args.includes('--index-only');
const onlyArg = args.find((a) => a.startsWith('--only'));
const only = onlyArg
  ? (onlyArg.includes('=') ? onlyArg.split('=')[1] : args[args.indexOf(onlyArg) + 1]).split(',')
  : null;

const THREADS = Number(process.env.THREADS ?? 1);
const CFM_STEPS = Number(process.env.CFM_STEPS ?? 2);
const SEED = 7;
const FALLBACK_RATE = 24000;

const { phrases } = JSON.parse(readFileSync(PHRASES_FILE, 'utf8'));
const lock = existsSync(LOCK_FILE) ? JSON.parse(readFileSync(LOCK_FILE, 'utf8')) : {};

// A clip is stale when its text or the render settings change.
const keyOf = (text) =>
  createHash('sha256').update(JSON.stringify({ text, CFM_STEPS, SEED, engine: 'chatterbox-mtl-q4' })).digest('hex').slice(0, 16);

function writeWav(path, samples, rate) {
  const data = Buffer.alloc(samples.length * 2);
  samples.forEach((s, i) => data.writeInt16LE(Math.max(-32768, Math.min(32767, Math.round(s))), i * 2));
  const h = Buffer.alloc(44);
  h.write('RIFF', 0); h.writeUInt32LE(36 + data.length, 4); h.write('WAVE', 8);
  h.write('fmt ', 12); h.writeUInt32LE(16, 16); h.writeUInt16LE(1, 20); h.writeUInt16LE(1, 22);
  h.writeUInt32LE(rate, 24); h.writeUInt32LE(rate * 2, 28); h.writeUInt16LE(2, 32); h.writeUInt16LE(16, 34);
  h.write('data', 36); h.writeUInt32LE(data.length, 40);
  writeFileSync(path, Buffer.concat([h, data]));
}

// Trim leading/trailing silence, even out loudness, encode AAC mono.
function encodeM4a(wav, m4a) {
  execFileSync('ffmpeg', [
    '-y', '-loglevel', 'error', '-i', wav,
    '-af', 'silenceremove=start_periods=1:start_threshold=-45dB,areverse,silenceremove=start_periods=1:start_threshold=-45dB,areverse,loudnorm=I=-16:TP=-1.5:LRA=11',
    '-ac', '1', '-ar', '24000', '-c:a', 'aac', '-b:a', '48k', m4a,
  ]);
}

function writeIndex() {
  const ids = Object.keys(phrases).filter((id) => existsSync(join(OUT_DIR, `${id}.m4a`)));
  const body = ids.map((id) => `  ${id}: require('../../assets/phrases/sw/${id}.m4a'),`).join('\n');
  writeFileSync(
    INDEX_FILE,
    `// Generated by scripts/phrases/generate.mjs. Do not edit by hand.\n` +
      `// One pre-rendered Chatterbox clip per phrase in assets/phrases/phrases.json.\n` +
      `export const PHRASE_ASSETS: Partial<Record<string, number>> = {\n${body}\n};\n`,
  );
  console.log(`wrote ${INDEX_FILE} (${ids.length}/${Object.keys(phrases).length} clips)`);
}

mkdirSync(OUT_DIR, { recursive: true });
if (indexOnly) {
  writeIndex();
  process.exit(0);
}

const todo = Object.entries(phrases).filter(([id, p]) => {
  if (only && !only.includes(id)) return false;
  if (force) return true;
  return !existsSync(join(OUT_DIR, `${id}.m4a`)) || lock[id] !== keyOf(p.sw);
});
console.log(`${todo.length} phrase(s) to render`);
if (todo.length === 0) {
  writeIndex();
  process.exit(0);
}

const sdk = await import(process.env.QVAC_SDK ? pathToFileURL(join(process.env.QVAC_SDK, 'dist/src/index.js')).href : '@qvac/sdk');
const { loadModel, unloadModel, textToSpeech, close, TTS_T3_MULTILINGUAL_CHATTERBOX_Q4_0, TTS_S3GEN_MULTILINGUAL_CHATTERBOX_Q4_0 } = sdk;

const modelId = await loadModel({
  modelSrc: TTS_T3_MULTILINGUAL_CHATTERBOX_Q4_0,
  modelConfig: {
    ttsEngine: 'chatterbox',
    language: 'sw',
    s3genModelSrc: TTS_S3GEN_MULTILINGUAL_CHATTERBOX_Q4_0,
    cfmSteps: CFM_STEPS,
    threads: THREADS,
    seed: SEED,
  },
});

try {
  for (const [id, p] of todo) {
    const t0 = Date.now();
    const r = textToSpeech({ modelId, text: p.sw, inputType: 'text', stream: false });
    const samples = await r.buffer;
    const rate = (await r.sampleRate) ?? FALLBACK_RATE;
    const wav = join(OUT_DIR, `${id}.wav`);
    writeWav(wav, samples, rate);
    encodeM4a(wav, join(OUT_DIR, `${id}.m4a`));
    unlinkSync(wav);
    lock[id] = keyOf(p.sw);
    // Save after every clip so an interrupted run keeps its progress.
    writeFileSync(LOCK_FILE, JSON.stringify(lock, null, 2) + '\n');
    writeIndex();
    console.log(`${id}: ${(samples.length / rate).toFixed(1)} s audio in ${((Date.now() - t0) / 1000).toFixed(0)} s  "${p.sw}"`);
  }
} finally {
  await unloadModel({ modelId, clearStorage: false });
  await close?.();
}
process.exit(0);
