// Expo config plugin: the UIScene life cycle on iOS, kept across
// `expo prebuild --clean`.
//
// iOS and iPadOS 27 stop an app at launch if it hasn't adopted scenes:
// UIKit traps in _UIApplicationEvaluateRuntimeIssueForNoSceneLifecycleAdoption
// before any app code runs. TestFlight build 2 was rejected for exactly that
// (App Review, iPad Air M4, iPadOS 27.2, 29 Oct). Expo SDK 54's AppDelegate
// makes its own UIWindow and has no scene manifest, so this plugin:
//
// 1. Adds UIApplicationSceneManifest to Info.plist: one window scene, handled
//    by SceneDelegate.
// 2. Writes SceneDelegate.swift and adds it to the app target. It makes the
//    window from the UIWindowScene and starts React Native in it, with the
//    factory the AppDelegate already set up.
// 3. Changes the AppDelegate to keep the launch options for the scene instead
//    of making a window. Prebuild fails if the template text it replaces has
//    changed, so an Expo upgrade can't silently drop the fix.
const { IOSConfig, withAppDelegate, withDangerousMod, withInfoPlist, withXcodeProject } = require('expo/config-plugins');
const fs = require('fs');
const path = require('path');

const SCENE_DELEGATE = `// Generated by plugins/withSceneLifecycle.js. Do not edit by hand.
import React
import UIKit

class SceneDelegate: UIResponder, UIWindowSceneDelegate {
  var window: UIWindow?

  func scene(
    _ scene: UIScene,
    willConnectTo session: UISceneSession,
    options connectionOptions: UIScene.ConnectionOptions
  ) {
    guard let windowScene = scene as? UIWindowScene,
          let appDelegate = UIApplication.shared.delegate as? AppDelegate,
          let factory = appDelegate.reactNativeFactory else { return }
    let window = UIWindow(windowScene: windowScene)
    // startReactNative sets the root view controller and makes the window key and visible.
    factory.startReactNative(
      withModuleName: "main",
      in: window,
      launchOptions: appDelegate.launchOptionsForScene)
    self.window = window
    // Code that still reads the app delegate's window (LogBox) finds this one.
    appDelegate.window = window
  }

  // Linking API: URLs opened while the app runs arrive at the scene, not the app delegate.
  func scene(_ scene: UIScene, openURLContexts URLContexts: Set<UIOpenURLContext>) {
    guard let url = URLContexts.first?.url else { return }
    _ = RCTLinkingManager.application(UIApplication.shared, open: url, options: [:])
  }
}
`;

const WINDOW_START = /( *)window = UIWindow\(frame: UIScreen\.main\.bounds\)\n\s*factory\.startReactNative\(\n\s*withModuleName: "main",\n\s*in: window,\n\s*launchOptions: launchOptions\)/;
const PROPERTY_ANCHOR = 'var reactNativeFactory: RCTReactNativeFactory?';

function adoptScenesInAppDelegate(contents) {
  if (contents.includes('launchOptionsForScene')) return contents;
  if (!WINDOW_START.test(contents) || !contents.includes(PROPERTY_ANCHOR)) {
    throw new Error(
      'withSceneLifecycle: the AppDelegate template changed; update plugins/withSceneLifecycle.js so the app still adopts scenes (iOS 27 traps without them).',
    );
  }
  return contents
    .replace(
      PROPERTY_ANCHOR,
      `${PROPERTY_ANCHOR}\n  /// Kept for SceneDelegate, which starts React Native once the window scene exists.\n  var launchOptionsForScene: [UIApplication.LaunchOptionsKey: Any]?`,
    )
    .replace(
      WINDOW_START,
      (_m, indent) => `${indent}// The window comes from the scene (SceneDelegate.swift): iOS 27 requires the scene life cycle.\n${indent}launchOptionsForScene = launchOptions`,
    );
}

const withSceneLifecycle = (config) => {
  config = withInfoPlist(config, (cfg) => {
    cfg.modResults.UIApplicationSceneManifest = {
      UIApplicationSupportsMultipleScenes: false,
      UISceneConfigurations: {
        UIWindowSceneSessionRoleApplication: [
          {
            UISceneConfigurationName: 'Default Configuration',
            UISceneDelegateClassName: '$(PRODUCT_MODULE_NAME).SceneDelegate',
          },
        ],
      },
    };
    return cfg;
  });

  config = withAppDelegate(config, (cfg) => {
    if (cfg.modResults.language !== 'swift') {
      throw new Error('withSceneLifecycle: expected a Swift AppDelegate.');
    }
    cfg.modResults.contents = adoptScenesInAppDelegate(cfg.modResults.contents);
    return cfg;
  });

  config = withDangerousMod(config, [
    'ios',
    (cfg) => {
      const projectName = IOSConfig.XcodeUtils.getProjectName(cfg.modRequest.projectRoot);
      const file = path.join(cfg.modRequest.platformProjectRoot, projectName, 'SceneDelegate.swift');
      fs.writeFileSync(file, SCENE_DELEGATE);
      return cfg;
    },
  ]);

  config = withXcodeProject(config, (cfg) => {
    const projectName = IOSConfig.XcodeUtils.getProjectName(cfg.modRequest.projectRoot);
    const filepath = `${projectName}/SceneDelegate.swift`;
    if (!cfg.modResults.hasFile(filepath)) {
      IOSConfig.XcodeUtils.addBuildSourceFileToGroup({
        filepath,
        groupName: projectName,
        project: cfg.modResults,
      });
    }
    return cfg;
  });

  return config;
};

module.exports = withSceneLifecycle;
module.exports.adoptScenesInAppDelegate = adoptScenesInAppDelegate;
